import express from "express";
import cors from "cors";
import helmet from "helmet";
import rateLimit from "express-rate-limit";
import morgan from "morgan";
import authRoutes from "./routes/auth.js";
import mealRoutes from "./routes/meals.js";
import adminRoutes from "./routes/admin.js";
import userRoutes from "./routes/user.js";
const app=express();
app.use(helmet());
app.use(cors({origin:process.env.CLIENT_URL||"http://localhost:5173",credentials:true}));
app.use(express.json({limit:"1mb"}));
app.use(morgan("dev"));
app.use("/api/auth",rateLimit({windowMs:15*60*1000,max:100}),authRoutes);
app.get("/api/health",(req,res)=>res.json({status:"ok",service:"Mondal Mess API"}));
app.use("/api/meals",mealRoutes);
app.use("/api/admin",adminRoutes);
app.use("/api/user",userRoutes);
app.use((req,res)=>res.status(404).json({message:"Route not found"}));
app.use((err,req,res,next)=>{console.error(err);res.status(err.status||500).json({message:err.code===11000?"Duplicate record":err.message||"Server error"});});
export default app;
